-- New Way's Community, Stage 4: comment protection and moderation (built and tested now; public comments arrive in
-- Stage 5). Adds four new tables only. No existing table or data is changed or removed.

-- The word lists Gary and Julie can edit in Admin (Community moderation > Word lists).
--   block = never published; hold = kept privately for Admin review; allow = innocent words never treated as a problem.
--   anywhere = also caught inside longer words (only for strong words with no innocent uses).
--   source: 'starter' (the list below) or 'admin' (added in Admin).
CREATE TABLE community_words (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  phrase TEXT NOT NULL UNIQUE,                       -- lower case, single spaces
  action TEXT NOT NULL CHECK (action IN ('block', 'hold', 'allow')),
  category TEXT NOT NULL DEFAULT '',                 -- swearing, hate, sexual, threat, abuse, innocent, other
  anywhere INTEGER NOT NULL DEFAULT 0,
  source TEXT NOT NULL DEFAULT 'admin' CHECK (source IN ('starter', 'admin')),
  added_by TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

-- Comments and replies on thank-you cards (empty until Stage 5). A blocked comment is never stored.
--   held = waiting privately for Admin; hidden = taken off the page (by Admin, or by three visitor reports) pending review;
--   rejected = turned down by Admin (kept briefly for the record). Deleting removes a comment completely.
--   official = 'gary' or 'julie' only for verified Admin comments (Stage 6), set by the server from the Admin sign-in.
CREATE TABLE community_comments (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  post_id INTEGER NOT NULL,
  parent_id INTEGER,                                 -- a reply's comment
  name TEXT NOT NULL DEFAULT '',
  body TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL CHECK (status IN ('published', 'held', 'hidden', 'rejected')),
  reasons TEXT NOT NULL DEFAULT '[]',                -- why it was held or hidden (for Admin)
  visitor_key TEXT NOT NULL DEFAULT '',              -- a scrambled code for the visitor (never their IP address)
  fingerprint TEXT NOT NULL DEFAULT '',              -- a scrambled code of the wording, to spot copied comments
  official TEXT NOT NULL DEFAULT '' CHECK (official IN ('', 'gary', 'julie')),
  admin_user_id INTEGER,
  approved_by TEXT NOT NULL DEFAULT '',              -- set when Gary or Julie approve or restore it
  approved_at TEXT,
  moderated_by TEXT NOT NULL DEFAULT '',
  moderated_at TEXT,
  report_count INTEGER NOT NULL DEFAULT 0,
  like_count INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX community_comments_post ON community_comments (post_id, status, id);
CREATE INDEX community_comments_status ON community_comments (status, created_at);
CREATE INDEX community_comments_fingerprint ON community_comments (fingerprint, created_at);
CREATE INDEX community_comments_visitor ON community_comments (visitor_key, created_at);

-- Visitor reports (the Report button arrives in Stage 5). One report per visitor per comment.
CREATE TABLE community_reports (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  comment_id INTEGER NOT NULL,
  reporter_key TEXT NOT NULL,
  counted INTEGER NOT NULL DEFAULT 1,                -- 0 when Admin has chosen to ignore that visitor's reports
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  UNIQUE (comment_id, reporter_key)
);

-- Repeat offenders, without accounts: a scrambled visitor code, never a name, email or IP address.
CREATE TABLE community_visitors (
  visitor_key TEXT PRIMARY KEY,
  strikes INTEGER NOT NULL DEFAULT 0,                -- blocked attempts in the last day
  blocked_total INTEGER NOT NULL DEFAULT 0,
  held_total INTEGER NOT NULL DEFAULT 0,
  last_strike_at TEXT,
  hold_until TEXT,                                   -- their comments are held for review until then
  always_hold INTEGER NOT NULL DEFAULT 0,            -- set by Gary or Julie
  reports_ignored INTEGER NOT NULL DEFAULT 0,        -- set by Gary or Julie: their reports no longer count
  last_name TEXT NOT NULL DEFAULT '',                -- the display name they last used (to recognise them in Admin)
  note TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

